// PayPal client: real sandbox (Invoicing v2 + Orders v2) or in-memory mock.
export interface InvoiceInput {
  recipientName: string;
  recipientEmail?: string;
  amount: number;
  currency?: string;
  description: string;
  dueDate?: string; // YYYY-MM-DD
}
export interface InvoiceSummary {
  id: string;
  status: string;
  recipientName: string;
  recipientEmail?: string;
  amount: number;
  currency: string;
  description: string;
  dueDate?: string;
  payerViewUrl?: string;
}
export interface PayPalApi {
  mode: "sandbox" | "mock";
  createInvoice(i: InvoiceInput): Promise<InvoiceSummary>;
  sendInvoice(id: string): Promise<InvoiceSummary>;
  remindInvoice(id: string): Promise<InvoiceSummary>;
  getInvoice(id: string): Promise<InvoiceSummary>;
  listInvoices(): Promise<InvoiceSummary[]>;
  createPaymentLink(amount: number, currency: string, description: string): Promise<{ orderId: string; approveUrl: string }>;
}

export class MockPayPal implements PayPalApi {
  mode = "mock" as const;
  private store = new Map<string, InvoiceSummary>();
  private n = 0;
  async createInvoice(i: InvoiceInput) {
    const id = `INV2-MOCK-${String(++this.n).padStart(4, "0")}`;
    const inv: InvoiceSummary = { id, status: "DRAFT", currency: i.currency ?? "USD", ...i };
    this.store.set(id, inv);
    return { ...inv };
  }
  private must(id: string) {
    const v = this.store.get(id);
    if (!v) throw new Error(`Invoice ${id} not found`);
    return v;
  }
  async sendInvoice(id: string) {
    const v = this.must(id);
    v.status = "SENT";
    v.payerViewUrl = `https://www.sandbox.paypal.com/invoice/p/#${id}`;
    return { ...v };
  }
  async remindInvoice(id: string) {
    const v = this.must(id);
    if (v.status === "DRAFT") throw new Error("Send the invoice before reminding");
    return { ...v };
  }
  async getInvoice(id: string) { return { ...this.must(id) }; }
  async listInvoices() { return [...this.store.values()].map((v) => ({ ...v })); }
  async createPaymentLink(amount: number, currency: string, _d: string) {
    const orderId = `MOCK-ORDER-${++this.n}`;
    return { orderId, approveUrl: `https://www.sandbox.paypal.com/checkoutnow?token=${orderId}` };
  }
}

export class SandboxPayPal implements PayPalApi {
  mode = "sandbox" as const;
  private token?: { v: string; exp: number };
  constructor(private id: string, private secret: string, private base = "https://api-m.sandbox.paypal.com", private invoicerEmail?: string) {}
  private async auth() {
    if (this.token && this.token.exp > Date.now()) return this.token.v;
    const r = await fetch(`${this.base}/v1/oauth2/token`, {
      method: "POST",
      headers: { Authorization: "Basic " + Buffer.from(`${this.id}:${this.secret}`).toString("base64"), "Content-Type": "application/x-www-form-urlencoded" },
      body: "grant_type=client_credentials",
    });
    if (!r.ok) throw new Error(`PayPal auth failed: ${r.status}`);
    const j = (await r.json()) as { access_token: string; expires_in: number };
    this.token = { v: j.access_token, exp: Date.now() + (j.expires_in - 60) * 1000 };
    return j.access_token;
  }
  private async call(path: string, method = "GET", body?: unknown): Promise<any> {
    const r = await fetch(`${this.base}${path}`, {
      method,
      headers: { Authorization: `Bearer ${await this.auth()}`, "Content-Type": "application/json", Prefer: "return=representation" },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await r.text();
    if (!r.ok) throw new Error(`PayPal ${method} ${path} -> ${r.status}: ${text.slice(0, 300)}`);
    return text ? JSON.parse(text) : {};
  }
  private map(j: any): InvoiceSummary {
    const item = j.items?.[0];
    const r = j.primary_recipients?.[0]?.billing_info;
    return {
      id: j.id, status: j.status,
      recipientName: [r?.name?.given_name, r?.name?.surname].filter(Boolean).join(" ") || "—",
      recipientEmail: r?.email_address,
      amount: Number(j.amount?.value ?? item?.unit_amount?.value ?? 0),
      currency: j.amount?.currency_code ?? item?.unit_amount?.currency_code ?? "USD",
      description: item?.name ?? (j.detail?.memo || ""),
      dueDate: j.detail?.payment_term?.due_date,
      payerViewUrl: j.detail?.metadata?.recipient_view_url,
    };
  }
  async createInvoice(i: InvoiceInput) {
    const { invoice_number } = await this.call("/v2/invoicing/generate-next-invoice-number", "POST");
    const cur = i.currency ?? "USD";
    const [given, ...rest] = i.recipientName.split(" ");
    const j = await this.call("/v2/invoicing/invoices", "POST", {
      detail: { invoice_number, currency_code: cur, note: "Generated by ENSIDEX Invoice Agent", ...(i.dueDate ? { payment_term: { due_date: i.dueDate } } : {}) },
      invoicer: this.invoicerEmail ? { email_address: this.invoicerEmail } : undefined,
      primary_recipients: [{ billing_info: { name: { given_name: given, surname: rest.join(" ") || undefined }, email_address: i.recipientEmail } }],
      items: [{ name: i.description, quantity: "1", unit_amount: { currency_code: cur, value: i.amount.toFixed(2) } }],
    });
    return this.map(j.id ? j : await this.call(j.href ? new URL(j.href).pathname : ""));
  }
  async sendInvoice(id: string) {
    // PayPal rejects emailing an invoice with no recipient email (MISSING_RECIPIENT_EMAIL);
    // in that case publish it as a shareable payer link instead.
    const cur = await this.getInvoice(id);
    await this.call(`/v2/invoicing/invoices/${id}/send`, "POST", cur.recipientEmail ? { send_to_invoicer: true } : { send_to_recipient: false, send_to_invoicer: false });
    return this.getInvoice(id);
  }
  async remindInvoice(id: string) { await this.call(`/v2/invoicing/invoices/${id}/remind`, "POST", { note: "Friendly reminder from ENSIDEX Team" }); return this.getInvoice(id); }
  async getInvoice(id: string) { return this.map(await this.call(`/v2/invoicing/invoices/${id}`)); }
  async listInvoices() {
    const j = await this.call("/v2/invoicing/invoices?page_size=20&total_required=true");
    // The list endpoint omits line items, so fetch details for item descriptions.
    return Promise.all((j.items ?? []).map((x: any) => this.getInvoice(x.id).catch(() => this.map(x))));
  }
  async createPaymentLink(amount: number, currency: string, description: string) {
    const j = await this.call("/v2/checkout/orders", "POST", {
      intent: "CAPTURE",
      purchase_units: [{ description, amount: { currency_code: currency, value: amount.toFixed(2) } }],
    });
    return { orderId: j.id, approveUrl: j.links?.find((l: any) => l.rel === "approve" || l.rel === "payer-action")?.href };
  }
}

export function makePayPal(env = process.env): PayPalApi {
  if (env.PAYPAL_CLIENT_ID && env.PAYPAL_CLIENT_SECRET)
    return new SandboxPayPal(env.PAYPAL_CLIENT_ID, env.PAYPAL_CLIENT_SECRET, env.PAYPAL_API_BASE, env.PAYPAL_INVOICER_EMAIL);
  return new MockPayPal();
}
